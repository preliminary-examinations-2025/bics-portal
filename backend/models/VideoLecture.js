const mongoose = require('mongoose');

const VideoLectureSchema = new mongoose.Schema({
    section: String,
    title: String,
    youtubeUrl: String,
    youtubeId: { type: String, index: true },
    durationSeconds: { type: Number, default: 0 },
    aiSummary: {
        synopsis: { type: String, default: '' },
        keyConcepts: [{ type: String }],
        detailedNotes: { type: String, default: '' },
        examTakeaways: [{ type: String }],
        generatedAt: { type: Date },
        provider: { type: String, default: '' } // 'groq', 'openrouter', or 'gemini'
    },
    createdAt: { type: Date, default: Date.now },
    hasPlayground: { type: Boolean, default: false },
    playgroundLanguage: { type: String, default: 'cpp' }, // 'cpp' or 'web'
    codeTemplate: { type: String, default: '' },
    webHtmlTemplate: { type: String, default: '' },
    webCssTemplate: { type: String, default: '' },
    webJsTemplate: { type: String, default: '' },

    // Exhaustive Knowledge Base (Generated by Gemini Ingestion Worker in 25-minute slices)
    knowledgeBase: {
        status: {
            type: String,
            enum: ['pending', 'in_progress', 'completed', 'failed'],
            default: 'pending',
            index: true
        },
        totalDurationMinutes: { type: Number, default: 0 },
        totalChunksExpected: { type: Number, default: 0 },
        completedChunksCount: { type: Number, default: 0 },
        synopsis: { type: String, default: '' },
        keyConcepts: [{ type: String }],
        chunks: [{
            chunkIndex: Number,
            startMinute: Number,
            endMinute: Number,
            status: { type: String, enum: ['pending', 'completed', 'failed'], default: 'pending' },
            topics: [{
                timestamp: String,        // e.g. "04:15"
                timestampSeconds: Number, // e.g. 255
                title: String,
                content: String,          // Dense ~100 words/min explanation
                codeOrFormula: String
            }],
            processedAt: Date
        }],
        attempts: { type: Number, default: 0 },
        lastAttemptAt: Date,
        lastError: String,
        flaggedForAdmin: { type: Boolean, default: false },
        failureDetails: { type: mongoose.Schema.Types.Mixed, default: null },
        completedAt: Date
    }
});

VideoLectureSchema.index({ 'knowledgeBase.status': 1, createdAt: 1 });

const VideoLectureModel = mongoose.model('VideoLecture', VideoLectureSchema);

module.exports = {
    VideoLectureSchema,
    VideoLectureModel
};
